#!/usr/bin/env bash
# vim: ft=sh
set -e

function excludedNimPackages() {
  local packages=""
  local vendor_dir
  for vendor_dir in "${NIMBUS_ETH1_REPO}"/vendor/nimbus-eth2/vendor/*; do
    [[ -d "${vendor_dir}" ]] || continue
    packages+="vendor/nimbus-eth2/vendor/$(basename "${vendor_dir}") "
  done
  echo "${packages}"
}

function buildBinaries() {

  cd "${NIMBUS_ETH1_REPO}"
  local COMMIT
  COMMIT=$(git rev-parse --short=8 HEAD)

  if [[ -f "build/nimbus_execution_client_${COMMIT}" ]]; then
    echo ">>> Binaries already exist for commit ${COMMIT}, no need to build a new nimbus binary!"
    return
  fi

  echo ">>> Building binaries for commit ${COMMIT}..."

  # callAndLogFunc runs a stage as part of an || list, which turns errexit off
  # in here, so a failed build has to be passed on explicitly

  # gcc, g++ and cc of the build come from here and not from the default of the OS
  local -x PATH="${BENCHMARK_TOOLCHAIN_BIN}:${PATH}"

  local COMPILER
  COMPILER="$(gcc --version | head -n 1)"
  if [[ "$(gcc -dumpversion | cut -d. -f1)" != "${BENCHMARK_GCC_VERSION}" ]]; then
    echo ">>> Expected GCC ${BENCHMARK_GCC_VERSION}, found: ${COMPILER:-no gcc at all}"
    return 1
  fi
  echo ">>> Compiler: ${COMPILER}"

  # The cached RocksDB libraries are only checked against the version of RocksDB,
  # ones left by another compiler have to go
  if [[ "$(cat "${ROCKSDB_CACHE_DIR}.compiler" 2>/dev/null)" != "${COMPILER}" ]]; then
    echo ">>> Compiler changed, dropping the cached RocksDB libraries"
    rm -rf "${ROCKSDB_CACHE_DIR}" || return 1
    echo "${COMPILER}" > "${ROCKSDB_CACHE_DIR}.compiler" || return 1
  fi

  local EXCLUDED_NIM_PACKAGES
  EXCLUDED_NIM_PACKAGES="$(excludedNimPackages)"

  # On a fresh clone the submodules of nimbus-eth2 do not exist yet, nothing is
  # excluded and this update fails after fetching them. The next one has the list.
  make -j16 update EXCLUDED_NIM_PACKAGES="${EXCLUDED_NIM_PACKAGES}" || true

  EXCLUDED_NIM_PACKAGES="$(excludedNimPackages)"

  make -j16 update EXCLUDED_NIM_PACKAGES="${EXCLUDED_NIM_PACKAGES}" || return 1
  make -j16 nimbus_execution_client \
    LOG_LEVEL="DEBUG" NIMFLAGS="-d:chronicles_colors=none -d:disableMarchNative" ROCKSDB_CI_CACHE="${ROCKSDB_CACHE_DIR}" \
    EXCLUDED_NIM_PACKAGES="${EXCLUDED_NIM_PACKAGES}" || return 1

  echo ">>> renaming binaries to match commit they were built from"
  mv "build/nimbus_execution_client" "build/nimbus_execution_client_${COMMIT}" || return 1

  echo ">>> creating a symbolic link to the latest version"
  ln -frs "build/nimbus_execution_client_${COMMIT}" build/nimbus_execution_client

  echo ">>> deleting copies that are older than N days"
  find build -mtime +3 -exec rm '{}' \+

}

function copyTemplateDatabase() {
  # errexit is off in here as well, see buildBinaries. Without the template nimbus
  # imports from genesis and the result would pass for a short benchmark.
  if [[ -z "$(ls -A "${NIMBUS_ETH1_TEMPLATE_DB}" 2>/dev/null)" ]]; then
    echo ">>> Template db ${NIMBUS_ETH1_TEMPLATE_DB} is missing or empty"
    return 1
  fi

  # this path is generated by nimbus, however in case of short benchmark this path may get cleaned up
  mkdir -p "${NIMBUS_ETH1_DB_DIR}" || return 1

  echo ">>> Copying template db into nimbus data directory"
  cp -r "${NIMBUS_ETH1_TEMPLATE_DB}/." "$NIMBUS_ETH1_DB_DIR/" || return 1
  echo ">>> Template db copied"

  echo ">>> making nimbus the owner of the copied files"
  chown -R "$(id -u -n):$(id -g -n)" "${NIMBUS_ETH1_DB_DIR}" || return 1
}
